int Font::textWidth(const char *text, int len)
{
    if (len == -1)
        len = strlen(text);
    int totalWidth = 0;
    for (int c = 0; c < len; ++c) {
        uint8_t ch = text[c];
        if (ch < firstChar) {
            totalWidth += spaceWidth;
            continue;
        }
        int width = xs[ch - firstChar + 1] - xs[ch - firstChar];
        totalWidth += width;
    }
    return totalWidth;
}

void Font::drawText(BaseDisplay &disp, Point pt, const char *text, int len)
{
    if (len == -1)
        len = strlen(text);
    auto fg = RGB565::rgb888(0xFF0000);
    auto bg = RGB565::rgb888(0xFFFF00);
    int pitch = (xs[sizeof(xs) / sizeof(xs[0]) - 1] + 7) >> 3;
    for (int c = 0; c < len; ++c) {
        uint8_t ch = text[c];
        if (ch < firstChar) {
            disp.fill(Rect(pt.x, pt.y, pt.x + spaceWidth, pt.y + height), bg);
            pt.x += spaceWidth;
            continue;
        }
        int pos = xs[ch - firstChar];
        int width = xs[ch - firstChar + 1] - pos;
        disp.copy1bit(pt, width, height, bits, pos, pitch, bg, fg);
        pt.x += width;
    }
}

